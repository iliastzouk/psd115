/**
 * Extract K4 slide bodies from PDF → src/data/week4/k4PptSlideBodies.generated.js
 * Run: node scripts/build-k4-slides.mjs
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { PDFParse } from 'pdf-parse'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const pdfPath = path.join(root, 'public', 'week4', 'k4-psd115.pdf')

const buf = fs.readFileSync(pdfPath)
const parser = new PDFParse({ data: buf })
const { text: raw } = await parser.getText()
await parser.destroy()

const re = /--\s*(\d+)\s+of\s+(\d+)\s*--/g
const parts = []
let m
let lastIndex = 0
let totalSlides = 0
while ((m = re.exec(raw)) !== null) {
  totalSlides = Math.max(totalSlides, parseInt(m[2], 10))
  if (parts.length) {
    parts[parts.length - 1].body = raw.slice(lastIndex, m.index).trim()
  }
  parts.push({ n: parseInt(m[1], 10), body: '' })
  lastIndex = m.index + m[0].length
}
if (parts.length) {
  parts[parts.length - 1].body = raw.slice(lastIndex).trim()
}

const bodies = {}
for (const { n, body } of parts) {
  bodies[n] = body.replace(/\r\n/g, '\n').trim()
}

const keys = Object.keys(bodies)
  .map(Number)
  .sort((a, b) => a - b)
const bodyLines = keys.map((n) => `  ${n}: ${JSON.stringify(bodies[n])},`)
const out = `/* Generated by scripts/build-k4-slides.mjs — do not edit by hand */
export const K4_PPT_TOTAL_SLIDES = ${totalSlides}
/** @type {Record<number, string>} */
export const K4_PPT_SLIDE_BODIES = {
${bodyLines.join('\n')}
}
`
const outPath = path.join(root, 'src', 'data', 'week4', 'k4PptSlideBodies.generated.js')
fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, out, 'utf8')
console.log('Wrote', outPath, keys.length, 'slides, K4_PPT_TOTAL_SLIDES =', totalSlides)
